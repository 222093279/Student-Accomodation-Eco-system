export interface MonthlyPerformanceRecord {
  monthKey: string; // e.g., '2025-03'
  monthLabel: string; // e.g., 'Mar 2025'
  shortMonth: string; // e.g., 'Mar'
  year: number;
  quarter: string; // e.g., 'Q1 2025'
  
  // Occupancy metrics
  totalBedsCapacity: number;
  occupiedBeds: number;
  occupancyRate: number; // percentage (0 - 100)
  blockAOccupancyRate: number;
  blockBOccupancyRate: number;
  singleSuitesOccupied: number;
  doubleBedsOccupied: number;
  vacantBeds: number;
  turnoverEvents: number;

  // Revenue metrics (in ZAR)
  targetRevenue: number;
  billedRevenue: number; // invoiced
  collectedRevenue: number; // actually paid
  pendingRevenue: number; // outstanding
  delinquentRevenue: number; // defaulted/written off
  maintenanceExpense: number; // upkeep costs
  netOperatingIncome: number; // collected - maintenance

  // Payment collection efficiency
  collectionRate: number; // percentage (collected / billed) * 100
  onTimePaymentsCount: number;
  gracePeriodPaymentsCount: number;
  latePaymentsCount: number;
  totalInvoicesIssued: number;
  averagePaymentDaysToClear: number; // e.g., 2.1 days
  
  // Academic context note
  academicMilestone?: string;
}

export interface PaymentChannelBreakdown {
  channel: string;
  count: number;
  totalAmount: number;
  percentage: number;
  color: string;
}

